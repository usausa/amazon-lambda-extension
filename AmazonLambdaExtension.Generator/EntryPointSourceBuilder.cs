namespace AmazonLambdaExtension.Generator;

using AmazonLambdaExtension.Generator.Models;

using SourceGenerateHelper;

internal static class EntryPointSourceBuilder
{
    private const string EntryPointNamespace = "AmazonLambdaExtension.Generated";
    private const string EntryPointClassName = "LambdaEntryPoint";
    private const string TaskType = "global::System.Threading.Tasks.Task";
    private const string LambdaContextType = "global::Amazon.Lambda.Core.ILambdaContext";
    private const string LambdaSerializerType = "global::Amazon.Lambda.Core.ILambdaSerializer";
    private const string LambdaBootstrapBuilderType = "global::Amazon.Lambda.RuntimeSupport.LambdaBootstrapBuilder";
    private const string LambdaBootstrapType = "global::Amazon.Lambda.RuntimeSupport.LambdaBootstrap";
    private const string InvalidOperationExceptionType = "global::System.InvalidOperationException";

    public static string HintName { get; } = HintNameBuilder.Build(EntryPointNamespace, EntryPointClassName);

    public static void Build(SourceBuilder builder, EntryPointModel entryPoint, IReadOnlyList<(LambdaModel Model, HandlerModel Handler)> handlers)
    {
        // _HANDLER で選んだハンドラーを Lambda ランタイムクライアントで動かす Main を生成（Native AOT のカスタムランタイム向け）
        // Generate Main that runs the handler selected by _HANDLER with the Lambda runtime client (for the Native AOT custom runtime)
        builder.AutoGenerated();
        builder.EnableNullable();
        builder.Disable("CS0612, CS0618");
        builder.NewLine();

        builder.Namespace(EntryPointNamespace);
        builder.NewLine();

        builder.AppendLine($"internal static class {EntryPointClassName}");
        builder.BeginScope();

        BuildMainMethod(builder, entryPoint, handlers);

        // 結果の有無で LambdaBootstrapBuilder.Create のオーバーロードが分かれるため、使う側だけを生成
        // LambdaBootstrapBuilder.Create overloads differ by whether a result exists, so generate only the ones in use
        if (handlers.Any(static x => LambdaSourceBuilder.GetEntryResultType(x.Handler) is not null))
        {
            builder.NewLine();
            BuildRunMethod(builder, hasResult: true);
        }

        if (handlers.Any(static x => LambdaSourceBuilder.GetEntryResultType(x.Handler) is null))
        {
            builder.NewLine();
            BuildRunMethod(builder, hasResult: false);
        }

        builder.EndScope();
    }

    public static string BuildHandlerName(EntryPointModel entryPoint, LambdaModel model, HandlerModel handler)
    {
        // マネージドランタイムと同じハンドラー名（{Assembly}::{Namespace}.{ClassName}::{Method}_Handler）にそろえる
        // Use the same handler name as the managed runtime ({Assembly}::{Namespace}.{ClassName}::{Method}_Handler)
        var typeName = String.IsNullOrEmpty(model.Namespace) ? model.ClassName : $"{model.Namespace}.{model.ClassName}";
        return $"{entryPoint.AssemblyName}::{typeName}::{handler.MethodName}_Handler";
    }

    private static void BuildMainMethod(SourceBuilder builder, EntryPointModel entryPoint, IEnumerable<(LambdaModel Model, HandlerModel Handler)> handlers)
    {
        builder.AppendLine($"public static async {TaskType} Main()");
        builder.BeginScope();

        // カスタムランタイムでは関数のハンドラー設定が _HANDLER に入る
        // On the custom runtime, the function's handler setting is passed in _HANDLER
        builder.AppendLine("var handler = global::System.Environment.GetEnvironmentVariable(\"_HANDLER\");");
        builder.AppendLine($"var serializer = new {entryPoint.SerializerType}();");
        builder.NewLine();

        builder.AppendLine("switch (handler)");
        builder.BeginScope();

        foreach (var (model, handler) in handlers)
        {
            var requestType = LambdaSourceBuilder.GetEntryRequestType(handler);
            var resultType = LambdaSourceBuilder.GetEntryResultType(handler);
            var typeArguments = resultType is not null ? $"{requestType}, {resultType}" : requestType;

            builder.AppendLine($"case {CSharpLiteral.Format(BuildHandlerName(entryPoint, model, handler))}:");
            builder.BeginScope();
            builder.AppendLine($"await RunAsync<{typeArguments}>({model.FunctionType.NonNullableFullName}.{handler.MethodName}_Handler, serializer).ConfigureAwait(false);");
            builder.AppendLine("return;");
            builder.EndScope();
        }

        // 未知のハンドラーは起動時に失敗させる。Runtime API があれば、初期化の関数で失敗させて init error として報告してから終える（マネージドのランタイムと同じ）
        // Fail at startup on an unknown handler. When the Runtime API exists, fail in the initializer so that it is reported as an init error before exiting (same as the managed runtime)
        builder.AppendLine("default:");
        builder.BeginScope();
        builder.AppendLine($"var exception = new {InvalidOperationExceptionType}($\"Handler is not found. handler=[{{handler}}]\");");
        builder.AppendLine("if (global::System.Environment.GetEnvironmentVariable(\"AWS_LAMBDA_RUNTIME_API\") is not null)");
        builder.BeginScope();
        builder.AppendLine($"using var bootstrap = new {LambdaBootstrapType}(_ => throw exception, () => throw exception);");
        builder.AppendLine("await bootstrap.RunAsync().ConfigureAwait(false);");
        builder.EndScope();
        builder.NewLine();
        builder.AppendLine("throw exception;");
        builder.EndScope();

        builder.EndScope();
        builder.EndScope();
    }

    private static void BuildRunMethod(SourceBuilder builder, bool hasResult)
    {
        var typeParameters = hasResult ? "TInput, TOutput" : "TInput";
        var resultType = hasResult ? $"{TaskType}<TOutput>" : TaskType;

        builder.AppendLine($"private static async {TaskType} RunAsync<{typeParameters}>(");
        builder.AppendLine($"    global::System.Func<TInput, {LambdaContextType}, {resultType}> handler,");
        builder.AppendLine($"    {LambdaSerializerType} serializer)");
        builder.BeginScope();
        builder.AppendLine($"using var bootstrap = {LambdaBootstrapBuilderType}.Create<{typeParameters}>(handler, serializer).Build();");
        builder.AppendLine("await bootstrap.RunAsync().ConfigureAwait(false);");
        builder.EndScope();
    }
}
